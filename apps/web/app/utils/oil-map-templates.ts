/*
 * Готовые раскладки для «Основа → Шаблон» при создании карты. Держателей нет — все точки
 * свободны. Координаты сняты в пикселях со скриншота карты и переводятся в проценты
 * квадратной рамки FRAME (центр XXL-01 — центр карты).
 */

export interface OilMapTemplatePoint {
  // уникальный ключ внутри шаблона: на исходной карте ромбы и квадраты делят номера
  key: string;
  type: OilPointType;
  name: string;
  x: number;
  y: number;
}

export interface OilMapTemplate {
  id: string;
  name: string;
  alliances: OilAlliance[];
  points: OilMapTemplatePoint[];
  links: [string, string][];
}

