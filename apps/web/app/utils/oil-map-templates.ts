const parseLinks =(text: string): [string, string][] =>
  text
    .split(/[|\n]/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((pair) => pair.split(/\s+/) as [string, string]);

const toPercent = (v: number, origin: number) =>
  Math.round(((v - origin) / FRAME.size) * 100 * 100) / 100;

